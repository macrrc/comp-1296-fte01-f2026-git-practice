def rectangle_area(length, width):
    """Calculates the area of a rectangle
    \nlength: (int or float) the longest side
    \nwidth: (int or float) the shortest side
    \n\nReturns the rectangles area
    """
    return length * width

def circle_area(radius):
    """Calculates the area of a circle using 3.14 for PI
    \nradius: (int or float) the circles radius
    \n\nreturns: the circle's area.
    """
    return 3.14 * (radius ** 2)

